        <div class="content-block">
            <h2>Why Verification Matters</h2>
            <p>Publishing inaccurate information — especially about individuals — can cause serious harm, damage reputations, and expose the organisation to legal risk. <strong>Verification is not optional.</strong> It is a core professional obligation.</p>
            <div class="quote-box">
                <strong>Privacy and accuracy are linked.</strong> If you publish personal information that is inaccurate, you may be in breach of both privacy principles and defamation or other laws.
            </div>
        </div>

        <div class="content-block">
            <h2>Steps for Verifying Information</h2>
            <ul class="numbered-list">
                <li><strong>Identify your source.</strong> Where did the information come from? Is the source reliable? Can the information be corroborated from another source?</li>
                <li><strong>Corroborate with at least one independent source.</strong> Do not publish on the basis of a single, unverified source unless there are exceptional circumstances and editorial approval.</li>
                <li><strong>Check documents carefully.</strong> If you are relying on documents (e.g., court records, company filings, leaked material), verify their authenticity and currency. Check dates, names, and details.</li>
                <li><strong>Be careful with social media.</strong> Social media content is often inaccurate, out-of-date, or taken out of context. Verify before relying on it.</li>
                <li><strong>Contact the person concerned (where appropriate).</strong> If the story involves allegations about an individual, give them an opportunity to respond <em>before</em> publication, unless there is a strong public interest reason not to.</li>
                <li><strong>Double-check names, titles, and positions.</strong> Spelling a person's name wrong is a common but avoidable error. It can also be a privacy issue if the wrong person is identified.</li>
            </ul>
        </div>

        <div class="content-block">
            <h2>Special Care With Personal Information</h2>
            <p>When handling personal information in the course of reporting, take these extra precautions:</p>

            <h3>Avoiding Misidentification</h3>
            <div class="principle-card" style="border-left-color: #d73a49;">
                <p>Misidentifying someone is one of the most serious privacy risks in news reporting. Before publishing a name, photo, or other identifying detail, take reasonable steps to confirm you have the <strong>right person</strong>.</p>
            </div>

            <h3>Children's Information</h3>
            <div class="principle-card" style="border-left-color: #d4a843;">
                <p>Extra caution is required when reporting on children. Consider whether publishing the information is necessary, whether consent has been obtained (parent/guardian), and whether the child could be identified from the published material.</p>
            </div>

            <h3>Sensitive Personal Information</h3>
            <div class="principle-card">
                <p>Information about a person's health, disability, race, ethnicity, religion, sexual orientation, or criminal record is <strong>sensitive information</strong> under privacy law. Think carefully before publishing such details — is there a clear public interest justification?</p>
            </div>
        </div>

        <div class="content-block">
            <h2>When You Cannot Verify — What to Do</h2>
            <p>Sometimes you may have information that appears credible but cannot be fully verified. In this situation:</p>
            <ul style="padding-left: 25px; margin: 15px 0;">
                <li style="margin-bottom: 8px;">Consider whether you can publish without naming the individual (e.g., "a senior official" instead of naming them).</li>
                <li style="margin-bottom: 8px;">Consider whether you can attribute the information to a named source ("According to X...") rather than presenting it as established fact.</li>
                <li style="margin-bottom: 8px;">Seek editorial guidance — do not guess or "hope for the best."</li>
            </ul>
        </div>

        <div class="content-block">
            <h2>Corrections and Take-down</h2>
            <p>If you realise that published information is inaccurate — especially if it involves personal information — <strong>act promptly</strong>:</p>
            <ul style="padding-left: 25px; margin: 15px 0;">
                <li style="margin-bottom: 8px;">Publish a correction as soon as possible, in a way that is visible and accessible.</li>
                <li style="margin-bottom: 8px;">Consider whether a take-down (removing the material entirely) is appropriate in the circumstances.</li>
                <li style="margin-bottom: 8px;">Notify the individual concerned, if appropriate, and explain what you have done.</li>
            </ul>
            <p>Prompt correction is not just good ethics — it may also reduce legal risk.</p>
        </div>

