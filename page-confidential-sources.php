            <h2>Legal Protections for Journalists' Sources</h2>
            <p>Australian law provides some protection for journalists' sources, but these protections are <strong>not absolute</strong>.</p>

            <h3>Journalist Source Protection Laws</h3>
            <div class="principle-card" style="border-left-color: #2c5282;">
                <p><strong>Evidence Acts (Cth, State & Territory)</strong> — Journalists have a limited protection from being compelled to disclose their sources in court proceedings. However, this protection can be overruled in certain circumstances (e.g., national security, serious criminal matters).</p>
            </div>

            <div class="principle-card" style="border-left-color: #d4a843;">
                <p><strong>Telecommunications (Interception and Access) Act 1979 (Cth)</strong> — Makes it an offence to intercept journalists' communications. However, this protection has been weakened by recent reforms and does not cover all forms of surveillance.</p>
            </div>

            <p style="margin-top: 20px;">Because legal protections are limited and subject to change, <strong>best practice is to treat all source arrangements as confidential by default</strong>, and to take active steps to protect source identity.</p>
        </div>

        <div class="content-block">
            <h2>Best Practice — Protecting Sources</h2>
            <ul class="numbered-list">
                <li><strong>Only collect source information that is necessary.</strong> Do not ask for, record, or store more personal information about a source than you actually need.</li>
                <li><strong>Use secure communication channels.</strong> Signal or other encrypted messaging tools are recommended for sensitive communications. Avoid using email or SMS for confidential source contact if possible.</li>
                <li><strong>Do not record source details in shared systems.</strong> If you must keep a record of a source's identity, keep it offline, secure, and separate from the story file.</li>
                <li><strong>Be careful with metadata.</strong> Digital files (photos, documents) can contain metadata that reveals who created them or where they were taken. Strip metadata before publishing or sharing.</li>
                <li><strong>Train all staff.</strong> Anyone who may come into contact with source material (editors, producers, support staff) must understand their obligations to protect source confidentiality.</li>
                <li><strong>Have a clear policy.</strong> The organisation should have a clear, written policy on source protection, and all staff should know where to find it and whom to ask if unsure.</li>
            </ul>
        </div>

        <div class="content-block">
            <h2>Confidential Information Beyond Sources</h2>
            <p>The obligation to protect confidential information is not limited to journalists' sources. It also applies to:</p>
            <ul style="padding-left: 25px; margin: 15px 0;">
                <li style="margin-bottom: 8px;"><strong>Editorial deliberations</strong> — Internal discussions about whether to publish, how to handle a story, or legal advice about publication should be kept confidential.</li>
                <li style="margin-bottom: 8px;"><strong>Commercial-in-confidence material</strong> — Information provided on the basis that it will not be published (e.g., commercial contracts, sensitive business data) should be handled carefully. Publication may be justified by public interest but requires editorial judgment.</li>
                <li style="margin-bottom: 8px;"><strong>Personal data collected in the course of reporting</strong> — If you collect personal information about individuals (e.g., through interviews, public records searches), you must handle it in accordance with privacy principles and the organisation's privacy policy.</li>
            </ul>
        </div>

        <div class="content-block">
            <h2>What to Do If Served with a Subpoena or Court Order</h2>
            <div class="quote-box" style="background: #fff5f5; border-left-color: #d73a49;">
                <p style="margin-top: 0; color: #d73a49; font-weight: 600;">⚠️ Important — Do not handle this alone.</p>
                <p>If you are served with a subpoena, court order, or other legal demand for source information or editorial material:</p>
                <ul style="padding-left: 20px; margin-bottom: 0;">
                    <li><strong>Do not ignore it.</strong> Court deadlines are strict.</li>
                    <li><strong>Contact the legal team / privacy officer immediately.</strong> They will advise on whether the demand is valid, whether protections apply, and how to respond.</li>
                    <li><strong>Do not voluntarily disclose</strong> more than is legally required.</li>
                </ul>
            </div>
