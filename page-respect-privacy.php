        <div class="content-block">
            <h2>Core Principle</h2>
            <div class="quote-box">
                <strong>Everyone has a right to privacy.</strong> The media serves the public interest by publishing information that matters. But publication must be justified by a <em>clear</em> public interest that outweighs the individual's right to privacy.
            </div>
            <p>The more sensitive the information, the stronger the public interest justification must be. If you are unsure whether publishing is justified, <strong>seek guidance</strong> from an editor or the privacy officer before proceeding.</p>
        </div>

        <div class="content-block">
            <h2>What Is "Public Interest"?</h2>
            <p>Public interest is not the same as "what the public is interested in." It means information that:</p>
            <ul class="numbered-list">
                <li>Exposes wrongdoing, corruption, or behaviour that affects the public</li>
                <li>Protects public health or safety</li>
                <li>Informs public debate on matters of importance to the community</li>
                <li>Prevents the public from being misled by someone's actions or statements</li>
                <li>Reveals significant incompetence or negligence in public office</li>
            </ul>
            <p style="margin-top: 20px;">Simply being "newsworthy" or attracting audience attention is <strong>not</strong> the same as being in the public interest.</p>
        </div>

        <div class="content-block">
            <h2>Sensitive Contexts — Extra Care Required</h2>
            <p>Some contexts require greater caution and a stronger public interest justification:</p>

            <h3>Children and Young People</h3>
            <div class="principle-card" style="border-left-color: #d4a843;">
                <p>Children have a stronger right to privacy than adults. Before publishing any material involving a child or young person, ask:</p>
                <ul style="padding-left: 25px; margin-top: 10px;">
                    <li>Is there a clear public interest in publishing this?</li>
                    <li>Would this put the child at risk of harm or identification in a sensitive situation?</li>
                    <li>Have we taken all reasonable steps to protect the child's privacy?</li>
                </ul>
            </div>

            <h3>Health and Personal Tragedy</h3>
            <div class="principle-card">
                <p>Avoid intrusive reporting on people experiencing personal tragedy (e.g., bereavement, severe illness, accident) unless there is a clear public interest justification.</p>
                <p style="margin-top: 10px;">Ask yourself: <em>Would I want this detail about my own family published in these circumstances?</em></p>
            </div>

            <h3>Family and Private Life</h3>
            <div class="principle-card">
                <p>Individuals have a right to keep their family relationships and private life private. Publishing details about someone's family, home life, or private relationships requires a strong public interest justification — simply because they are "connected to a public figure" is rarely enough.</p>
            </div>
        </div>

        <div class="content-block">
            <h2>Places Where Privacy Is Expected</h2>
            <p>People have a "reasonable expectation of privacy" in certain places. Taking photos, recording, or conducting interviews in these places raises special concerns:</p>
            <table class="checklist-table" style="margin-top: 15px;">
                <thead>
                    <tr>
                        <th>Place</th>
                        <th>Expectation of Privacy</th>
                        <th>Before Publishing</th>
                    </tr>
                </thead>
                <tbody>
                    <tr>
                        <td><strong>Home / private residence</strong></td>
                        <td>High</td>
                        <td>Strong public interest required; generally avoid photography at private homes</td>
                    </tr>
                    <tr>
                        <td><strong>Hospital / medical facility</strong></td>
                        <td>High</td>
                        <td>Consent usually required; be mindful of patient privacy laws</td>
                    </tr>
                    <tr>
                        <td><strong>School (of children)</strong></td>
                        <td>High</td>
                        <td>Parent/guardian consent; consider child's best interests</td>
                    </tr>
                    <tr>
                        <td><strong>Public street</strong></td>
                        <td>Lower</td>
                        <td>Still consider whether focus on individuals is justified</td>
                    </tr>
                    <tr>
                        <td><strong>Workplace (public-facing)</strong></td>
                        <td>Moderate</td>
                        <td>Depends on context; public officials have lower expectation</td>
                    </tr>
                </tbody>
            </table>
        </div>

        <div class="content-block">
            <h2>Questions to Ask Before Publishing</h2>
            <div style="background: #fff8e7; border-left: 4px solid #d4a843; padding: 20px 25px; border-radius: 0 8px 8px 0; margin-top: 15px;">
                <p style="margin-top: 0; font-weight: 600; color: #1e3a5f;">Before publishing any material that touches on privacy, ask yourself:</p>
                <ul style="padding-left: 25px; margin-bottom: 0;">
                    <li>Is there a <strong>clear public interest</strong> in publishing this?</li>
                    <li>Is the information <strong>necessary</strong> for the story, or is it just "colour"?</li>
                    <li>Is the person a <strong>public figure</strong> or in a role that attracts public scrutiny?</li>
                    <li>Does the person have a <strong>reasonable expectation of privacy</strong> in this context?</li>
                    <li>Have I taken <strong>reasonable steps</strong> to verify the information?</li>
                    <li>Would I be comfortable explaining this decision <strong>publicly</strong>?</li>
                </ul>
            </div>
