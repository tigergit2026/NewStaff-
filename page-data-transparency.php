            <h2>Why Transparency Matters</h2>
            <p>Audiences trust news organisations with their personal information — when they visit our website, sign up for newsletters, participate in surveys, or contact us. <strong>Transparency about how we use that data is both a legal obligation and a trust-building measure.</strong></p>
            <div class="quote-box">
                <strong>Key principle:</strong> People have a right to know what personal information is being collected, why it is being collected, and how it will be used.
            </div>
