        <div class="content-block">
            <h2>When Do We Collect Personal Information?</h2>
            <p>Be aware of the many ways personal information may be collected in the course of news work:</p>
            <ul style="padding-left: 25px; margin: 15px 0;">
                <li style="margin-bottom: 8px;"><strong>Audience interactions:</strong> Comments, emails, letters to the editor, survey responses</li>
                <li style="margin-bottom: 8px;"><strong>Newsletter subscriptions:</strong> Email addresses, demographic information</li>
                <li style="margin-bottom: 8px;"><strong>Website analytics:</strong> IP addresses, device information, browsing behaviour (often collected via cookies/third-party tools)</li>
                <li style="margin-bottom: 8px;"><strong>Social media:</strong> Information shared publicly or via direct message</li>
                <li style="margin-bottom: 8px;"><strong>Reporting:</strong> Interviews, public records searches, interactions with sources and subjects</li>
                <li style="margin-bottom: 8px;"><strong>Commercial activities:</strong> Advertising, events, subscriptions</li>
            </ul>
        </div>

        <div class="content-block">
            <h2>Your Transparency Obligations</h2>

            <h3>1. Have a Clear, Accessible Privacy Policy</h3>
            <div class="principle-card" style="border-left-color: #2c5282;">
                <p>The organisation must have a privacy policy that is easy to find and easy to understand. It should explain what personal information is collected, why, how it is used, and who it may be disclosed to. <strong>If you don't know where the privacy policy is — find out.</strong></p>
            </div>

            <h3>2. Notify When Collecting Personal Information</h3>
            <div class="principle-card" style="border-left-color: #d4a843;">
                <p>Where possible, individuals should be <strong>informed</strong> when their personal information is being collected. This might be through a privacy notice on a form, a statement on a survey, or a disclaimer in an interview setting (where appropriate).</p>
            </div>

            <h3>3. Only Use Information for the Stated Purpose</h3>
            <div class="principle-card" style="border-left-color: #2c5282;">
                <p>Personal information collected for one purpose (e.g., to respond to a comment) should not be used for another purpose (e.g., added to a marketing database) without consent or a valid exception. This is a core requirement of APP 6.</p>
            </div>

            <h3>4. Be Careful With Third-Party Tools</h3>
            <div class="principle-card" style="border-left-color: #d4a843;">
                <p>Many news websites use third-party tools (analytics, advertising, social plugins) that collect user data. Understand what these tools collect and ensure the privacy policy discloses this. If you are responsible for website content, <strong>check what tracking tools are in use</strong>.</p>
            </div>
        </div>

        <div class="content-block">
            <h2>Practical Guidance — What You Can Do</h2>
            <ul class="numbered-list">
                <li><strong>Know where the privacy policy is</strong> and be able to point audiences to it if they ask.</li>
                <li><strong>Be thoughtful about what you collect.</strong> Do not collect personal information "just in case" — only collect what you actually need.</li>
                <li><strong>Be careful with cookies and tracking.</strong> If you are involved in website management, ensure cookie banners and consent mechanisms are in place where required.</li>
                <li><strong>Respect "do not track" requests.</strong> If someone asks to be removed from a database or to have their information deleted, take it seriously and involve the privacy officer if needed.</li>
                <li><strong>Train yourself.</strong> Make sure you understand the basics of how the organisation handles personal information — this is part of your professional responsibility.</li>
            </ul>
        </div>

