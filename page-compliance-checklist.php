        <div class="content-block">
            <h2>DO — Privacy Compliance</h2>
            <table class="checklist-table">
                <thead>
                    <tr>
                        <th style="width: 50%;">Action</th>
                        <th style="width: 50%;">Why It Matters</th>
                    </tr>
                </thead>
                <tbody>
                    <tr>
                        <td class="do-item" style="padding-left: 35px;"><strong>Seek guidance</strong> from an editor or privacy officer when unsure about a privacy issue</td>
                        <td>Privacy issues can be complex. Getting a second opinion helps you avoid mistakes and shows due diligence.</td>
                    </tr>
                    <tr>
                        <td class="do-item" style="padding-left: 35px;"><strong>Verify information</strong> before publishing, especially personal details</td>
                        <td>Inaccurate publication can cause harm and legal risk. Verification is a core professional duty.</td>
                    </tr>
                    <tr>
                        <td class="do-item" style="padding-left: 35px;"><strong>Consider public interest</strong> — is there a clear justification for publishing?</td>
                        <td>Privacy is not absolute, but the justification must be real, not just "it's newsworthy."</td>
                    </tr>
                    <tr>
                        <td class="do-item" style="padding-left: 35px;"><strong>Take extra care with children</strong> and vulnerable people</td>
                        <td>Children have a stronger right to privacy. The public interest bar is higher.</td>
                    </tr>
                    <tr>
                        <td class="do-item" style="padding-left: 35px;"><strong>Protect confidential sources</strong> — use secure channels and store details safely</td>
                        <td>Source protection is an ethical and sometimes legal obligation. Breaching it damages trust and may have legal consequences.</td>
                    </tr>
                    <tr>
                        <td class="do-item" style="padding-left: 35px;"><strong>Be transparent</strong> about how you collected information and what you will use it for</td>
                        <td>Transparency builds audience trust and is a legal requirement under APP 5.</td>
                    </tr>
                    <tr>
                        <td class="do-item" style="padding-left: 35px;"><strong>Offer a response opportunity</strong> to people who are the subject of critical coverage</td>
                        <td>Fairness and accuracy — and it reduces legal risk.</td>
                    </tr>
                    <tr>
                        <td class="do-item" style="padding-left: 35px;"><strong>Correct inaccuracies promptly</strong> if you publish something wrong</td>
                        <td>Prompt correction demonstrates professionalism and helps mitigate legal risk.</td>
                    </tr>
                </tbody>
            </table>
        </div>

        <div class="content-block">
            <h2>DON'T — Privacy Compliance</h2>
            <table class="checklist-table">
                <thead>
                    <tr>
                        <th style="width: 50%;">Avoid This</th>
                        <th style="width: 50%;">What Could Go Wrong</th>
                    </tr>
                </thead>
                <tbody>
                    <tr>
                        <td class="dont-item" style="padding-left: 35px;">Assume that all personal information <strong>can be published</strong> simply because it was obtained legally</td>
                        <td>Legal acquisition ≠ free to publish. Privacy principles and public interest still apply.</td>
                    </tr>
                    <tr>
                        <td class="dont-item" style="padding-left: 35px;">Use <strong>deception or surreptitious methods</strong> without a strong public interest justification</td>
                        <td>Deception may breach ethical standards and legal obligations. Must be justified and approved.</td>
                    </tr>
                    <tr>
                        <td class="dont-item" style="padding-left: 35px;">Harass, pursue, or photograph people <strong>in places where they have a reasonable expectation of privacy</strong></td>
                        <td>This can breach privacy laws and APC principles. Intrusion must be justified.</td>
                    </tr>
                    <tr>
                        <td class="dont-item" style="padding-left: 35px;">Publish <strong>sensitive personal information</strong> (health, race, religion, sexuality) without a clear public interest justification</td>
                        <td>Sensitive information is subject to higher protection under privacy law and ethical standards.</td>
                    </tr>
                    <tr>
                        <td class="dont-item" style="padding-left: 35px;">Share confidential source information <strong>with people who don't need to know</strong></td>
                        <td>Breaches confidentiality, may expose sources to harm, and may have legal consequences.</td>
                    </tr>
                    <tr>
                        <td class="dont-item" style="padding-left: 35px;">Collect or store <strong>more personal information than you need</strong></td>
                        <td>Excessive data collection breaches APP 3 and creates unnecessary privacy risk.</td>
                    </tr>
                    <tr>
                        <td class="dont-item" style="padding-left: 35px;">Assume that the <strong>journalism exemption</strong> gives you a "free pass" on privacy</td>
                        <td>The exemption is conditional and does not remove ethical obligations or all legal risk.</td>
                    </tr>
                    <tr>
                        <td class="dont-item" style="padding-left: 35px;">Ignore a <strong>subpoena or court order</strong> — always seek legal advice immediately</td>
                        <td>Ignoring a court order can result in contempt of court. The legal team can advise on protections.</td>
                    </tr>
                </tbody>
            </table>
        </div>

