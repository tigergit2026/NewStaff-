        </div>

        <div class="content-block">
            <h2>How to Use This Checklist</h2>
            <p>Use this checklist <strong>before publishing</strong> any material that involves personal information or touches on privacy. It is a quick-reference guide — not a substitute for judgment or for seeking advice when unsure.</p>
            <div class="quote-box" style="background: #fff8e7; border-left-color: #d4a843;">
                <strong>⚠️ When in doubt — ask.</strong> If you are unsure about a privacy issue, seek guidance from an editor or the privacy officer <em>before</em> publishing.
            </div>
