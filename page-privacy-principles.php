            <h1>Privacy Principles</h1>
            <p class="page-subtitle">Understanding the Australian Press Council's Statement of Privacy Principles and the Australian Privacy Principles (APPs)</p>
        </div>

        <div class="content-block">
            <h2>Overview</h2>
            <p>All staff must understand and apply privacy principles in their daily work. These principles come from two main sources:</p>
            <ul style="padding-left: 25px; margin: 15px 0;">
                <li style="margin-bottom: 10px;"><strong>Australian Press Council (APC) — Statement of Privacy Principles</strong><br>Applies specifically to news media work.</li>
                <li style="margin-bottom: 10px;"><strong>Australian Privacy Principles (APPs)</strong><br>Set out in the <em>Privacy Act 1988</em> (Cth), apply to how we handle personal information.</li>
            </ul>
        </div>

        <div class="content-block">
            <h2>APC Statement of Privacy Principles</h2>
            <p>The APC's Statement of Privacy Principles sets out how the news media should handle privacy. The key principles are summarised below.</p>

            <div class="principle-card">
                <span class="principle-number">1</span><h3>Public Interest Test</h3>
                <p>Privacy is not an absolute right. Publication is justified when there is a <strong>clear public interest</strong> that outweighs an individual's right to privacy. The more sensitive the information, the stronger the public interest justification must be.</p>
            </div>

            <div class="principle-card">
                <span class="principle-number">2</span><h3>Children and Young People</h3>
                <p>Extra care must be taken when publishing material about children. Their right to privacy is stronger than that of adults, and the public interest justification must be correspondingly stronger.</p>
            </div>

            <div class="principle-card">
                <span class="principle-number">3</span><h3>Health and Personal Tragedy</h3>
                <p>Avoid intrusive reporting on people experiencing personal tragedy or serious health issues, unless there is a clear public interest justification.</p>
            </div>

            <div class="principle-card">
                <span class="principle-number">4</span><h3>Family and Private Life</h3>
                <p>Respect individuals' right to keep their family and private life private. Publication of details about private life requires a strong public interest justification.</p>
            </div>

            <div class="principle-card">
                <span class="principle-number">5</span><h3>Harassment and Pursuit</h3>
                <p>Do not harass, pursue, or photograph individuals in a way that invades their privacy, especially in places where they have a reasonable expectation of privacy (e.g., their home).</p>
            </div>

            <div class="principle-card">
                <span class="principle-number">6</span><h3>Deception</h3>
                <p>Avoid the use of deception, surreptitious methods, or misrepresentation to obtain material, unless there is a strong public interest justification and no other way to obtain the information.</p>
            </div>

            <div class="principle-card highlight">
                <span class="principle-number">7</span><h3>Consent and Awareness</h3>
                <p>Where possible, seek consent before publishing private information. Individuals should be aware that information they provide may be published, unless there is a strong public interest reason not to inform them.</p>
            </div>

            <div class="principle-card">
                <span class="principle-number">8</span><h3>Correction and Response</h3>
                <p>Offer individuals who are the subject of critical privacy-related coverage a reasonable opportunity to respond, and correct any inaccuracies promptly.</p>
            </div>
        </div>

        <div class="content-block">
            <h2>Australian Privacy Principles (APPs)</h2>
            <p>The APPs are part of the <em>Privacy Act 1988</em> (Cth) and apply to how organisations handle personal information. Key APPs relevant to news media include:</p>

            <div style="background: #f8f9fa; border-radius: 8px; padding: 25px; margin-top: 20px;">
                <h3 style="color: #1e3a5f; font-size: 16px; margin-top: 0;">APP 1 — Open and Transparent Management</h3>
                <p style="font-size: 14px;">Have a clear privacy policy and be open about how personal information is handled.</p>
            </div>

            <div style="background: #f8f9fa; border-radius: 8px; padding: 25px; margin-top: 15px;">
                <h3 style="color: #1e3a5f; font-size: 16px; margin-top: 0;">APP 3 — Collection of Personal Information</h3>
                <p style="font-size: 14px;">Only collect personal information that is necessary, and collect it by lawful and fair means.</p>
            </div>

            <div style="background: #f8f9fa; border-radius: 8px; padding: 25px; margin-top: 15px;">
                <h3 style="color: #1e3a5f; font-size: 16px; margin-top: 0;">APP 5 — Notification of Collection</h3>
                <p style="font-size: 14px;">Notify individuals when their personal information is collected, and how it will be used.</p>
            </div>

            <div style="background: #f8f9fa; border-radius: 8px; padding: 25px; margin-top: 15px;">
                <h3 style="color: #1e3a5f; font-size: 16px; margin-top: 0;">APP 6 — Use or Disclosure</h3>
                <p style="font-size: 14px;">Only use or disclose personal information for the purpose for which it was collected, unless an exception applies (e.g., consent, or a relevant exemption).</p>
            </div>

            <div style="background: #f8f9fa; border-radius: 8px; padding: 25px; margin-top: 15px;">
                <h3 style="color: #1e3a5f; font-size: 16px; margin-top: 0;">APP 11 — Security of Personal Information</h3>
                <p style="font-size: 14px;">Protect personal information from misuse, interference, loss, and unauthorised access or disclosure.</p>
            </div>
        </div>

        <div class="content-block">
            <h2>Journalism Exemption</h2>
            <div class="quote-box">
                <p>The <em>Privacy Act 1988</em> contains a <strong>journalism exemption</strong>. This means that certain APP obligations do not apply to an act done in the course of journalism, where the organisation is publicly committed to publishing a privacy policy and observing privacy standards.</p>
                <p style="margin-top: 10px;">However, this exemption is not absolute. It does not give journalists a "free pass" on privacy. Ethical judgment and public interest still apply.</p>
            </div>
